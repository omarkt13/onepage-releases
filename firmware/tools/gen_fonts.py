#!/usr/bin/env python3
"""Generates 1-bit bitmap fonts for the Windows-1252 range (0x20..0xFF).

    python3 -I firmware/tools/gen_fonts.py firmware/src/ui/fonts_generated.c

Needs Pillow and the DejaVu fonts (fonts-dejavu-core on Debian/Ubuntu).
DejaVu is under the Bitstream Vera licence, which permits embedding.
The output is committed, so a firmware build does not need Pillow.
"""
import sys

from PIL import Image, ImageDraw, ImageFont

DEJAVU = "/usr/share/fonts/truetype/dejavu/"

# name, file, pixel size, characters (None = full 0x20..0xFF)
FONTS = [
    ("font_ui", "DejaVuSans.ttf", 26, None),
    ("font_ui_bold", "DejaVuSans-Bold.ttf", 30, None),
    ("font_title", "DejaVuSans-Bold.ttf", 40, None),
    ("font_clock", "DejaVuSans.ttf", 120, "0123456789: apm"),
    ("font_read_s", "DejaVuSerif.ttf", 26, None),
    ("font_read_m", "DejaVuSerif.ttf", 32, None),
    ("font_read_l", "DejaVuSerif.ttf", 40, None),
]

FIRST, LAST = 0x20, 0xFF


def char_for(code):
    try:
        return bytes([code]).decode("cp1252")
    except UnicodeDecodeError:
        return None


def render(path, size, subset):
    font = ImageFont.truetype(path, size)
    ascent, descent = font.getmetrics()
    height = ascent + descent
    glyphs = []
    data = bytearray()
    for code in range(FIRST, LAST + 1):
        ch = char_for(code)
        if ch is None or (subset is not None and ch not in subset):
            glyphs.append((0, 0, 0, 0, 0, 0))
            continue
        adv = int(round(font.getlength(ch)))
        img = Image.new("L", (adv + size, height + size // 2), 0)
        ImageDraw.Draw(img).text((size // 4, 0), ch, font=font, fill=255)
        bw = img.point(lambda v: 255 if v >= 110 else 0).convert("1")
        bbox = bw.getbbox()
        if bbox is None:
            glyphs.append((len(data), adv, 0, 0, 0, 0))
            continue
        x0, y0, x1, y1 = bbox
        w, h = x1 - x0, y1 - y0
        off = len(data)
        row_bytes = (w + 7) // 8
        for y in range(y0, y1):
            row = bytearray(row_bytes)
            for x in range(x0, x1):
                if bw.getpixel((x, y)):
                    row[(x - x0) // 8] |= 0x80 >> ((x - x0) % 8)
            data += row
        glyphs.append((off, adv, w, h, x0 - size // 4, y0))
    return height, ascent, glyphs, data


def main():
    out = sys.argv[1]
    lines = [
        "/* Generated by firmware/tools/gen_fonts.py. Do not edit. */",
        "/* Glyphs: DejaVu fonts, Bitstream Vera licence. */",
        "#include \"fonts.h\"",
        "",
    ]
    for name, file, size, subset in FONTS:
        height, ascent, glyphs, data = render(DEJAVU + file, size, subset)
        lines.append(f"static const uint8_t {name}_bits[] = {{")
        for i in range(0, len(data), 16):
            lines.append("\t" + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
        lines.append("};")
        lines.append(f"static const struct font_glyph {name}_glyphs[] = {{")
        for off, adv, w, h, x, y in glyphs:
            lines.append(f"\t{{{off}, {adv}, {w}, {h}, {x}, {y}}},")
        lines.append("};")
        lines.append(f"const struct font {name} = {{")
        lines.append(f"\t.height = {height}, .ascent = {ascent}, .first = 0x{FIRST:02x}, "
                     f".last = 0x{LAST:02x},")
        lines.append(f"\t.glyphs = {name}_glyphs, .bits = {name}_bits,")
        lines.append("};")
        lines.append("")
    with open(out, "w") as f:
        f.write("\n".join(lines))


if __name__ == "__main__":
    main()
